export function principleFor(code: CauseCode, position: number): string | null {
  const entry = PRINCIPLES[code];
  if (!entry) return null;
  return entry[groupOf(position)] ?? entry.any ?? null;
}

// When the role isn't known (a trend over mixed roles): the shared version,
// else the core one - the advice most players in that spot need.
export function principleForAnyRole(code: CauseCode): string | null {
  const entry = PRINCIPLES[code];
  if (!entry) return null;
  return entry.any ?? entry.carry ?? entry.mid ?? entry.offlane ?? null;
}
