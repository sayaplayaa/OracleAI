// What each position is actually responsible for, per phase of the game, plus
// which end-of-game stats are worth judging for it. The coach is only given
// its own role's block: judging a carry on healing or a support on last hits
// produces exactly the useless advice this exists to prevent.
//
// The wording is distilled from what top coaches teach in their videos and
// guides (mainly Ueio, plus BalloonDota, PainDota, Support Heaven and
// others) - see docs/coach-knowledge.md for the sources and rule IDs. The
// model writes its report in Russian, so this is written in Russian too -
// the text below goes straight into the prompt the model reads.

export interface RoleProfile {
  position: number;
  label: string;
  isCore: boolean;
  // MatchMetrics.stats labels worth judging for this role (kit-dependent ones
  // are additionally checked against the hero's real abilities).
  relevantStats: string[];
  job: { laning: string; midGame: string; lateGame: string };
  // Human-readable list of things never to give this role advice about.
  neverAdviseOn: string[];
  // Where this role does and doesn't belong on the map, by stage.
  mapRules: string;
  // Backstop: report findings matching any of these are dropped for this role.
  // The model writes Russian, so these match Russian coaching vocabulary (and
  // common English jargon players mix in, like GPM/XPM/KDA).
  irrelevantAdvice: RegExp[];
}

// JS `\b` only knows ASCII word characters, so it never fires next to a
// Cyrillic letter - word edges here are `(?<!\p{L})` / `(?!\p{L})` instead.
const VISION = /вард|обсервер|сентри|(?<!\p{L})вижен|observer|sentry|\bwards?\b/iu;
// A core buying its own 1-2 safety wards is fine; deward and sentry duty is a support's job.
const DEEP_VISION_DUTY = /девард|деворд|сентри|sentry|\bdewards?\b/iu;
const HEALING = /(?<!\p{L})лечени|(?<!\p{L})лечит|исцел|(?<!\p{L})хил(?:ом|а|ить|ит|ишь)?(?!\p{L})|\bheal/iu;
const STUNS = /(?<!\p{L})стан(?:ы|ов|а|ом|ами|ить)?(?!\p{L})|оглуш|\bstuns?\b/iu;
const HERO_DAMAGE = /урон\s+по\s+геро|урон[а-яё\s]{0,12}в\s+минуту|dmg\s*\/\s*min|hero damage/iu;
const FARM_STATS =
  /добивани|\bgpm\b|золот[оа]\s+в\s+минуту|\bxpm\b|опыт[а]?\s+в\s+минуту|нетворс|net worth|(?<!\p{L})фарм/iu;

